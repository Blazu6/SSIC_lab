bool is_weak_des_key(const uint8_t* key_chunk) 
{
    for (const auto& weak_key : WEAK_KEYS) 
    {
        if (memcmp(key_chunk, weak_key.data(), 8) == 0) 
        {
            return true;
        }
    }
    return false;
}

bool is_3des_key_safe(const uint8_t* key) 
{
    if (is_weak_des_key(key) ||           // checks bytes 0-7
        is_weak_des_key(key + 8) ||       // checks bytes 8-15
        is_weak_des_key(key + 16))         // checks bytes 16-23
        {     
            return false;
        }
    if (memcmp(key, key + 8, 8) == 0 || memcmp(key + 8, key + 16, 8) == 0 || memcmp(key, key + 16, 8) == 0) 
    {
        return false;
    }
    return true; 
}

bool encrypt_3des_ctr(const std::string& in_filename, const std::string& out_filename, const uint8_t* key, const uint8_t* iv) 
{
    std::ifstream in_file(in_filename, std::ios::binary);
    std::ofstream out_file(out_filename, std::ios::binary);

    if (!in_file || !out_file) 
    {
        std::cerr << "Blad: Nie mozna otworzyc plikow." << std::endl;
        return false;
    }

    uint8_t counter[8]; //copy IV to counter to be able to decrypt cause we need to start with the same IV for both encryption and decryption
    std::memcpy(counter, iv, 8);

    EVP_CIPHER_CTX* ctx = EVP_CIPHER_CTX_new(); //initialization of the context for encryption/decryption
    EVP_EncryptInit_ex(ctx, EVP_des_ede3(), NULL, key, NULL); // 3DES in ECB mode, because we will handle the CTR logic ourselves
    EVP_CIPHER_CTX_set_padding(ctx, 0); // CTR mode does not use padding, so we disable it

    const size_t CHUNK_SIZE = 1024 * 1024;
    std::vector<uint8_t> buffer(CHUNK_SIZE);// buffor to fetch data from file in chunks of 1MB, we will process this buffer in blocks of 8 bytes (size of 3DES block)

    uint8_t keystream[8]; // Buffer to hold the encrypted counter (the keystream block)
    int outlen;

    std::cout << "Szyfrowanie/Deszyfrowanie w toku... Proszę czekać." << std::endl;

    while (in_file) 
    {
        in_file.read(reinterpret_cast<char*>(buffer.data()), CHUNK_SIZE);//we need to change the type of buffer to char* because the read function expects a pointer to char
        size_t bytes_read = in_file.gcount();
        if (bytes_read == 0) break;// End of file reached, exit loop

        for (size_t i = 0; i < bytes_read; i += 8) 
        {
            EVP_EncryptUpdate(ctx, keystream, &outlen, counter, 8); // Encrypt the counter to produce the keystream block

            size_t block_limit = std::min((size_t)8, bytes_read - i); // Calculate how many bytes to process in this block (could be less than 8 for the last block)
            
            for (size_t j = 0; j < block_limit; ++j) 
            {
                buffer[i + j] ^= keystream[j]; // xor the data with the keystream (key stream is the encrypted counter)
            }

            for (int k = 7; k >= 0; --k) 
            {
                if (++counter[k] != 0) break; // Increment the counter (big-endian), if it overflows, continue to the next byte
            }
        }
        
        out_file.write(reinterpret_cast<char*>(buffer.data()), bytes_read);
    }

    std::cout << "Operacja zakonczona sukcesem!" << std::endl;

    EVP_CIPHER_CTX_free(ctx);
    in_file.close();
    out_file.close();


    return true;
}

bool verify_files(const std::string& path1, const std::string& path2) 
{
    std::ifstream f1(path1, std::ios::binary | std::ios::ate);
    std::ifstream f2(path2, std::ios::binary | std::ios::ate);

    if (!f1.is_open() || !f2.is_open()) return false;

    if (f1.tellg() != f2.tellg()) return false; // Different file sizes

    f1.seekg(0, std::ios::beg);
    f2.seekg(0, std::ios::beg);

    const size_t VERIFY_BUF_SIZE = 8192;
    std::vector<char> buf1(VERIFY_BUF_SIZE);
    std::vector<char> buf2(VERIFY_BUF_SIZE);

    while (f1 && f2) 
    {
        f1.read(buf1.data(), VERIFY_BUF_SIZE);
        f2.read(buf2.data(), VERIFY_BUF_SIZE);

        if (f1.gcount() != f2.gcount()) return false;
        
        if (std::memcmp(buf1.data(), buf2.data(), f1.gcount()) != 0) return false;
    }

    return true;
}

